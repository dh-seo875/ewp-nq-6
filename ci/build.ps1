[CmdletBinding()]
param(
    [string]$Uv4Executable = $(
        if ($env:KEIL_UV4_PATH) {
            $env:KEIL_UV4_PATH
        }
        else {
            'C:\Keil_v5\UV4\UV4.exe'
        }
    ),
    [string]$TargetName = 'iEWP'
)

$ErrorActionPreference = 'Stop'
Set-StrictMode -Version 2.0

$repositoryRoot = (Resolve-Path (Join-Path $PSScriptRoot '..')).Path
$projectRoot = Join-Path $repositoryRoot 'Src'
$projectFile = Join-Path $projectRoot 'iEWP.uvprojx'
$objectDirectory = Join-Path $projectRoot 'Objects'
$listingDirectory = Join-Path $projectRoot 'Listings'
$artifactDirectory = Join-Path $repositoryRoot 'build'
$buildLogPath = Join-Path $artifactDirectory 'keil-build.log'

function Assert-FileExists {
    param(
        [Parameter(Mandatory = $true)]
        [string]$Path,
        [Parameter(Mandatory = $true)]
        [string]$Description
    )

    if (-not (Test-Path -LiteralPath $Path -PathType Leaf)) {
        throw "$Description not found: $Path"
    }
}

try {
    Write-Host '============================================================'
    Write-Host 'iEWP Keil5 Headless Build'
    Write-Host "Repository : $repositoryRoot"
    Write-Host "Project    : $projectFile"
    Write-Host "Target     : $TargetName"
    Write-Host "Keil       : $Uv4Executable"
    Write-Host "Computer   : $env:COMPUTERNAME"
    Write-Host "User       : $env:USERNAME"
    Write-Host '============================================================'

    Assert-FileExists -Path $Uv4Executable -Description 'Keil executable'
    Assert-FileExists -Path $projectFile -Description 'Keil project'

    New-Item -ItemType Directory -Force -Path $artifactDirectory | Out-Null

    $artifacts = @(
        [PSCustomObject]@{
            Source = Join-Path $objectDirectory 'iEWP.axf'
            Name = 'iEWP.axf'
        },
        [PSCustomObject]@{
            Source = Join-Path $objectDirectory 'iEWP.hex'
            Name = 'iEWP.hex'
        },
        [PSCustomObject]@{
            Source = Join-Path $listingDirectory 'iEWP.map'
            Name = 'iEWP.map'
        }
    )

    # Remove exact previous outputs so stale repository files cannot pass CI checks.
    foreach ($artifact in $artifacts) {
        if (Test-Path -LiteralPath $artifact.Source) {
            Remove-Item -LiteralPath $artifact.Source -Force
        }
    }

    if (Test-Path -LiteralPath $buildLogPath) {
        Remove-Item -LiteralPath $buildLogPath -Force
    }

    $buildStartedAt = (Get-Date).AddSeconds(-2)

    Write-Host ''
    Write-Host '[1/2 Keil full rebuild]'
    & $Uv4Executable `
        -r $projectFile `
        -t $TargetName `
        -j0 `
        -o $buildLogPath

    $buildExitCode = $LASTEXITCODE

    if (Test-Path -LiteralPath $buildLogPath) {
        Write-Host ''
        Write-Host '[Keil build log]'
        Get-Content -LiteralPath $buildLogPath
    }
    else {
        Write-Warning "Keil build log was not generated: $buildLogPath"
    }

    if ($buildExitCode -ge 2) {
        throw "Keil build failed with exit code $buildExitCode."
    }

    if ($buildExitCode -eq 1) {
        Write-Warning 'Keil build completed with warnings.'
    }

    Write-Host ''
    Write-Host '[2/2 Artifact verification]'

    foreach ($artifactDefinition in $artifacts) {
        Assert-FileExists -Path $artifactDefinition.Source -Description 'Build artifact'

        $artifact = Get-Item -LiteralPath $artifactDefinition.Source
        if ($artifact.Length -le 0) {
            throw "Build artifact is empty: $($artifact.FullName)"
        }
        if ($artifact.LastWriteTime -lt $buildStartedAt) {
            throw "Build artifact was not regenerated by this build: $($artifact.FullName)"
        }

        Copy-Item -LiteralPath $artifact.FullName `
            -Destination (Join-Path $artifactDirectory $artifactDefinition.Name) `
            -Force

        Write-Host ("[OK] {0} ({1} bytes)" -f $artifact.FullName, $artifact.Length)
    }

    Write-Host ''
    Write-Host '[PASS] iEWP Keil5 Headless Build completed.'
    Write-Host "Artifacts: $artifactDirectory"
    exit 0
}
catch {
    Write-Error $_
    Write-Host '[FAIL] iEWP Keil5 Headless Build failed.'
    exit 1
}
